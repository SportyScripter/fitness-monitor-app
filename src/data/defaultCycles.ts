// Helper to build pre-calculated week maps for default cycles
const generateDefaultWeeksMap = (
  baseDays: WorkoutDay[],
  weeks: MesocyclePhase[]
): Record<number, WorkoutDay[]> => {
  const map: Record<number, WorkoutDay[]> = {};
  weeks.forEach((phase) => {
    map[phase.week] = baseDays.map((d) => ({
      ...d,
      id: `w${phase.week}-${d.dayNumber}-${d.id}`,
      exercises: (d.exercises || []).map((ex) => ({
        ...ex,
        id: `ex-w${phase.week}-${ex.name.replace(/\s+/g, '-').toLowerCase()}`,
        defaultWeightKg: phase.isDeload
          ? Math.round(ex.defaultWeightKg * 0.7)
          : Math.round(ex.defaultWeightKg * (phase.volumeMultiplier >= 0.5 ? phase.volumeMultiplier : 1.0)),
      })),
      sessionNotes: phase.progressionNote || d.sessionNotes,
    }));
  });
  return map;
};

